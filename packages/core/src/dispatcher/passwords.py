"""Salted Argon2id hashes for explicitly configured, temporary operator logins."""

import re
import secrets

from cryptography.exceptions import InvalidKey
from cryptography.hazmat.primitives.kdf.argon2 import Argon2id

# OWASP's minimum Argon2id profile; keep generation and accepted PHC parameters together.
_MEMORY_KIB = 19456
_ITERATIONS = 2
_LANES = 1
_SALT_BYTES = 16
_KEY_BYTES = 32
_PHC = re.compile(
    rf"\$argon2id\$v=19\$m={_MEMORY_KIB},t={_ITERATIONS},p={_LANES}"
    r"\$[A-Za-z0-9+/]{22}\$[A-Za-z0-9+/]{43}"
)


def hash_password(password: str) -> str:
    """Generate a salted PHC value; callers must never persist the input password."""
    return Argon2id(
        salt=secrets.token_bytes(_SALT_BYTES),
        length=_KEY_BYTES,
        iterations=_ITERATIONS,
        lanes=_LANES,
        memory_cost=_MEMORY_KIB,
    ).derive_phc_encoded(password.encode())


def validate_password_hash(encoded: str) -> str:
    """Reject malformed or unexpected KDF settings before accepting deployment config."""
    if not _PHC.fullmatch(encoded):
        raise ValueError("Test login requires an Argon2id hash generated by password_hash.py")
    return encoded


def verify_password(password: str, encoded: str) -> bool:
    """Use the cryptographic library's constant-time verification of a validated PHC value."""
    try:
        Argon2id.verify_phc_encoded(password.encode(), encoded)
        return True
    except InvalidKey:
        return False
